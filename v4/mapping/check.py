"""Offline checks for the question mapping, and the coverage table.

Checks: every item in questions.json has a row in mapping.csv; every assistant draft maps to at
least one concern that exists in concerns.md; every concern has at least one item. Renders
coverage.md and coverage.tex (concerns by frameworks, item counts). No model calls.
Run from the repository root: python3 v4/mapping/check.py
"""
import csv
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
Q = json.loads((HERE / "questions.json").read_text())
FW = ["BB", "ECBD", "SC", "H2B", "ABC", "CAL", "OECD"]
FW_NAMES = {k: Q["frameworks"][k]["name"] for k in FW}
COL = "final"  # the column used for the coverage table; falls back to assistant_draft when empty


def concerns():
    out = {}
    for line in (HERE / "concerns.md").read_text().splitlines():
        m = re.match(r"\| (C\d\d) \| ([^|]+) \|", line)
        if m:
            out[m.group(1)] = m.group(2).strip()
    return out


def main():
    C = concerns()
    rows = list(csv.DictReader((HERE / "mapping.csv").open()))
    by_id = {r["item_id"]: r for r in rows}
    errors = []
    items = {i["id"]: i for i in Q["items"]}
    for iid in items:
        if iid not in by_id:
            errors.append(f"no mapping row for {iid}")
    used = defaultdict(lambda: defaultdict(int))  # concern -> framework -> item count
    column_used = defaultdict(int)
    for r in rows:
        if r["item_id"] not in items:
            errors.append(f"mapping row for unknown item {r['item_id']}")
            continue
        cell = r[COL].strip() or r["assistant_draft"].strip()
        column_used[COL if r[COL].strip() else "assistant_draft"] += 1
        ids = [c.strip() for c in cell.split(";") if c.strip()]
        if not ids:
            errors.append(f"{r['item_id']} maps to no concern")
        for c in ids:
            if c not in C:
                errors.append(f"{r['item_id']} maps to unknown concern {c}")
            used[c][r["framework"]] += 1
    for c in C:
        if not used[c]:
            errors.append(f"concern {c} has no item")
    # coverage table
    lines = ["# Coverage of shared concerns by framework", "",
             f"Generated by check.py from mapping.csv (column: {dict(column_used)}). Cells are item counts. A concern with one framework only is a coverage finding.", "",
             "| Id | Concern | " + " | ".join(FW_NAMES[f] for f in FW) + " | Frameworks |",
             "|---|---|" + "---|" * (len(FW) + 1)]
    tex = ["\\begin{table*}[t]", "\\caption{Shared review concerns and the number of items each framework spends on them (RQ1). Empty cells mean the framework has no item for the concern.}",
           "\\label{tab:coverage}", "\\small", "\\begin{tabular}{@{}llrrrrrrrr@{}}", "\\toprule",
           "Id & Concern & BetterBench & ECBD & Scorecard & How2Bench & Checklist & Caliper & OECD & Frameworks \\\\", "\\midrule"]
    shared_all = shared_some = one = 0
    for c, name in C.items():
        counts = [used[c].get(f, 0) for f in FW]
        n = sum(1 for x in counts if x)
        if n == len(FW):
            shared_all += 1
        elif n == 1:
            one += 1
        elif n > 1:
            shared_some += 1
        lines.append(f"| {c} | {name} | " + " | ".join(str(x) if x else "" for x in counts) + f" | {n} |")
        tex.append(f"{c} & {name} & " + " & ".join(str(x) if x else "" for x in counts) + f" & {n} \\\\")
    tex += ["\\bottomrule", "\\end{tabular}", "\\end{table*}"]
    lines += ["", f"Concerns asked by all seven frameworks: {shared_all}. By more than one: {shared_some}. By one only: {one}.", "",
              "Items per framework: " + ", ".join(f"{FW_NAMES[f]} {Q['counts'][f]}" for f in FW) + "."]
    (HERE / "coverage.md").write_text("\n".join(lines) + "\n")
    (HERE / "coverage.tex").write_text("\n".join(tex) + "\n")
    summary = {"items": len(items), "concerns": len(C), "shared_by_all": shared_all, "shared_by_some": shared_some, "one_framework": one,
               "errors": errors}
    print(json.dumps(summary, indent=1))
    sys.exit(1 if errors else 0)


if __name__ == "__main__":
    main()
